-- 6. FUNCIONES RPC
CREATE OR REPLACE FUNCTION public.submit_lead_feedback(p_lead_id UUID, p_rating TEXT)
RETURNS VOID AS $$
BEGIN
  UPDATE public.leads
  SET feedback_rating = p_rating, feedback_responded_at = now()
  WHERE id = p_lead_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.submit_lead_survey(p_lead_id UUID, p_survey_data JSONB)
RETURNS VOID AS $$
BEGIN
  UPDATE public.leads
  SET survey_data = p_survey_data
  WHERE id = p_lead_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.increment_email_open(tracking_id UUID)
RETURNS VOID AS $$
BEGIN
  UPDATE public.email_tracking
  SET 
    opens_count = opens_count + 1,
    last_opened_at = now(),
    first_opened_at = COALESCE(first_opened_at, now()),
    status = 'opened'
  WHERE id = tracking_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

